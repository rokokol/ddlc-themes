#!/usr/bin/env bash
set -euo pipefail

here="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
out="$here/dist"
src="$here/src"
vendor="$here/vendor"

usage() {
  cat <<EOF
generate.sh — render the kitty, btop, matplotlib, Claude Code and opencode themes, the
web kit, the report stylesheet, the letter styles and the syntax table out of ddlc-palette

It writes dist/, committed for consumers without Nix: run it after the palette moves, or
after an edit to src/, and commit the result with the rendered files. It reads src/ and
vendor/ beside itself

  --light FILE     base16-ddlc-light.yaml   (or \$DDLC_BASE16_LIGHT)
  --dark FILE      base16-ddlc-dark.yaml    (or \$DDLC_BASE16_DARK)
  --palette FILE   palette.env              (or \$DDLC_PALETTE_ENV)
  --nerd FILE      DepartureMono.tar.xz     (or \$DDLC_NERD_DEPARTURE)

The schemes and the palette come from ddlc-palette, the archive from the Nerd Fonts release,
and nix develop puts each of them in the environment already. Without Nix, take them there:

  curl -sSLO https://raw.githubusercontent.com/rokokol/ddlc-palette/master/dist/base16-ddlc-dark.yaml
  curl -sSLO https://raw.githubusercontent.com/rokokol/ddlc-palette/master/dist/palette.env
  curl -sSLO https://github.com/ryanoasis/nerd-fonts/releases/latest/download/DepartureMono.tar.xz
EOF
}

declare -A scheme=(
  [light]="${DDLC_BASE16_LIGHT:-}"
  [dark]="${DDLC_BASE16_DARK:-}"
)
palette_env="${DDLC_PALETTE_ENV:-}"
nerd_archive="${DDLC_NERD_DEPARTURE:-}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --light)
      scheme[light]="${2:?file required}"
      shift 2
      ;;
    --dark)
      scheme[dark]="${2:?file required}"
      shift 2
      ;;
    --palette)
      palette_env="${2:?file required}"
      shift 2
      ;;
    --nerd)
      nerd_archive="${2:?file required}"
      shift 2
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      usage >&2
      exit 1
      ;;
  esac
done

# The kitty and btop tables below name base16 slots, so resolve them once per variant. $V picks
# the variant
declare -A slot
for variant in light dark; do
  file="${scheme[$variant]}"
  [ -n "$file" ] || {
    echo "generate.sh: no $variant scheme — pass --$variant or set DDLC_BASE16_${variant^^}" >&2
    exit 1
  }
  n=0
  while read -r key hex; do
    slot["$variant/$key"]="$hex"
    n=$((n + 1))
  done < <(sed -n 's/^  \(base[0-9A-F][0-9A-F]\): "\(#[0-9A-F]\{6\}\)".*/\1 \2/p' "$file")
  # Sixteen slots or it is not a base16 scheme, and a half-read file would render a half-theme
  [ "$n" = 16 ] || {
    echo "generate.sh: $file has $n slots, want 16" >&2
    exit 1
  }
done
s() { printf '%s' "${slot["$V/$1"]}"; }

# The other themes have more roles than sixteen slots, so their tables name palette colours
# directly and resolve against the flat name=HEX form. The hex comes in bare — matplotlib wants
# it that way (its parser treats the rest of an rcparam value after a "#" as a comment, so a
# quoted "#BB5599" reads as an unterminated string and the whole cycler is silently discarded
# for the stock one) — and the JSON writers put the "#" back on
[ -n "$palette_env" ] || {
  echo "generate.sh: no palette — pass --palette or set DDLC_PALETTE_ENV" >&2
  exit 1
}
declare -A pal
pal_names=()
while read -r name hex; do
  pal[$name]="$hex"
  pal_names+=("$name")
done < <(sed -n 's/^\([A-Za-z][A-Za-z0-9]*\)=\([0-9A-F]\{6\}\)$/\1 \2/p' "$palette_env")
[ "${#pal_names[@]}" -gt 0 ] || {
  echo "generate.sh: $palette_env holds no name=HEX lines" >&2
  exit 1
}

# A table naming a colour the palette does not have is a typo or a rename that got away. Either
# would ship a theme with a hole in it, so refuse the whole run before writing any of it
need() { # <theme> <name>...
  local theme="$1" name
  shift
  for name in "$@"; do
    [[ $name == "-" || $name == "none" || -n ${pal[$name]:-} ]] || {
      echo "generate.sh: $theme names $name, which the palette does not have" >&2
      exit 1
    }
  done
}

mkdir -p "$out"
banner="Generated by generate.sh from ddlc-palette's base16 schemes — do not edit"
named_banner="Generated by generate.sh from ddlc-palette's colours — do not edit"

for V in light dark; do

  # Slot for slot the mapping tinted-theming/tinted-kitty uses, with one departure: it grounds
  # the selection in base03, which leaves base05 on it at 1.65:1 here, so base02 carries it.
  # The light column departs further, because the palette is polarised and one slot does not
  # read the same on both grounds. Bright black is base02 (natsuki) on paper at 1.4:1, and it
  # carries shell suggestions and dimmed output, so light takes base03 (jacket, 2.6:1). The
  # cursor, links, the active border and the active tab take base0E (plum), the colour of the
  # site's own links and download button; paper on plum holds 4.3:1
  kitty_slots="background             base00  base00
foreground             base05  base05
selection_background   base02  base02
selection_foreground   base05  base05
cursor                 base05  base0E
cursor_text_color      base00  base00
url_color              base04  base0E
active_border_color    base03  base0E
inactive_border_color  base01  base01
wayland_titlebar_color base00  base00
macos_titlebar_color   base00  base00
active_tab_background  base00  base0E
active_tab_foreground  base05  base00
inactive_tab_background base01 base01
inactive_tab_foreground base04 base04
tab_bar_background     base01  base01

color0                 base00  base00
color1                 base08  base08
color2                 base0B  base0B
color3                 base0A  base0A
color4                 base0D  base0D
color5                 base0E  base0E
color6                 base0C  base0C
color7                 base05  base05
color8                 base02  base03
color9                 base08  base08
color10                base0B  base0B
color11                base0A  base0A
color12                base0D  base0D
color13                base0E  base0E
color14                base0C  base0C
color15                base07  base07
color16                base09  base09
color17                base0F  base0F
color18                base01  base01
color19                base02  base02
color20                base04  base04
color21                base06  base06"
  col=2
  [[ $V == light ]] && col=3
  {
    echo "# $banner"
    echo "# vim:ft=kitty"
    echo "# Include this from kitty.conf: include ddlc-kitty-$V.conf"
    echo
    # A blank line in the table separates the chrome from the ANSI colours, as in the output
    while read -r line; do
      [ -n "$line" ] || {
        echo
        continue
      }
      read -r key slot_name <<<"$(awk -v c="$col" '{ print $1, $c }' <<<"$line")"
      echo "$key $(s "$slot_name")"
    done <<<"$kitty_slots"
  } >"$out/ddlc-kitty-$V.conf"

  # btop has no base16 template anywhere upstream, so this mapping is local. Meters that carry no
  # scale are one colour — btop reads that as a start with an empty mid and end
  {
    echo "# $banner"
    echo "# Drop into ~/.config/btop/themes/ and select it with color_theme=\"ddlc-$V\""
    echo
    echo "theme[main_bg]=\"$(s base00)\""
    echo "theme[main_fg]=\"$(s base05)\""
    echo "theme[title]=\"$(s base06)\""
    echo "theme[hi_fg]=\"$(s base0A)\""
    echo "theme[selected_bg]=\"$(s base02)\""
    echo "theme[selected_fg]=\"$(s base06)\""
    echo "theme[inactive_fg]=\"$(s base03)\""
    echo "theme[graph_text]=\"$(s base04)\""
    echo "theme[meter_bg]=\"$(s base01)\""
    echo "theme[proc_misc]=\"$(s base0B)\""
    echo "theme[cpu_box]=\"$(s base0D)\""
    echo "theme[mem_box]=\"$(s base0B)\""
    echo "theme[net_box]=\"$(s base0E)\""
    echo "theme[proc_box]=\"$(s base0C)\""
    echo "theme[div_line]=\"$(s base03)\""
    # Load rises through the palette's warm accents: green, then yellow, then red
    for gradient in temp cpu process; do
      echo "theme[${gradient}_start]=\"$(s base0B)\""
      echo "theme[${gradient}_mid]=\"$(s base0A)\""
      echo "theme[${gradient}_end]=\"$(s base08)\""
    done
    while read -r meter slot_name; do
      echo "theme[${meter}_start]=\"$(s "$slot_name")\""
      echo "theme[${meter}_mid]=\"\""
      echo "theme[${meter}_end]=\"\""
    done <<'METERS'
