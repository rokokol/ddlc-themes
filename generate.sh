  } >"$out/ddlc-btop-$V.theme"

done

# --- matplotlib -------------------------------------------------------------------------------
# matplotlib finds a named style by filename under stylelib/, so the file name is the API:
# plt.style.use("ddlc"). The module name is too — import ddlc_cmaps — hence its underscore

mpl_cycle_light="plum bow rule monikaEye yuri"
mpl_cycle_dark="plum bow rule"
# shellcheck disable=SC2086 # the cycles are word lists on purpose
need matplotlib paper ink jacket ash yuri dot pink sayoriEye skirt bow bowShadow sayori \
  $mpl_cycle_light $mpl_cycle_dark

mpl_cycler() {
  local sep='' cyc='' c
  for c in "$@"; do
    cyc+="$sep'${pal[$c]}'"
    sep=', '
  done
  printf "axes.prop_cycle:  cycler('color', [%s])\n" "$cyc"
}

mpl_colours() { # ground ink muted grid
  cat <<EOF
figure.facecolor:  ${pal[$1]}
savefig.facecolor: ${pal[$1]}
axes.facecolor:    ${pal[$1]}
axes.edgecolor:    ${pal[$4]}
grid.color:        ${pal[$4]}

text.color:        ${pal[$2]}
axes.labelcolor:   ${pal[$2]}
axes.titlecolor:   ${pal[$2]}
xtick.color:       ${pal[$3]}
ytick.color:       ${pal[$3]}
xtick.labelcolor:  ${pal[$2]}
ytick.labelcolor:  ${pal[$2]}
EOF
}

# No axes.grid in here: it would mean "on every axes", and a heatmap or an image draws above
# the grid whatever axisbelow says, so the lines end up cutting across the data. A chart that
# wants one calls ax.grid(axis="y") for the direction its values actually run.
# The face is Nunito, the prose face. matplotlib reads no variation axis, so a variable
# Nunito draws in its default instance, ExtraLight, and has no bold: the title stays
# normal, or every chart would log that it found no bold weight
mpl_common() {
  cat <<'EOF'
figure.dpi:          140
savefig.dpi:         140
savefig.bbox:        tight
font.family:         sans-serif
font.sans-serif:     Nunito, DejaVu Sans
font.size:           9
axes.titlesize:      11
axes.titleweight:    normal
axes.titlelocation:  left
axes.spines.top:     False
axes.spines.right:   False
axes.axisbelow:      True
grid.linewidth:      0.7
legend.frameon:      False
lines.linewidth:     1.8
EOF
}

{
  echo "# $named_banner"
  echo "# Copy into ~/.config/matplotlib/stylelib/ and select it: plt.style.use(\"ddlc\")"
  echo
  echo "# A chart assigns series from this list in order, and the order is the safety mechanism"
  echo "# rather than a taste: adjacent entries are what a stacked bar or a multi-line chart puts"
  echo "# side by side. Each neighbour pair clears deuteranopia and protanopia"
  echo "# (Machado-Oliveira-Fernandes 2009 at severity 1.0) by OKLab distance x100 >= 8, and"
  echo "# >= 15 unsimulated. Reordering is a visible change even though no colour moves"
  # shellcheck disable=SC2086 # the cycle is a word list on purpose
  mpl_cycler $mpl_cycle_light
  echo
  mpl_colours paper ink jacket ash
  echo
  mpl_common
} >"$out/ddlc.mplstyle"

{
  echo "# $named_banner"
  echo "# Copy into ~/.config/matplotlib/stylelib/ and select it: plt.style.use(\"ddlc-dark\")"
  echo
  echo "# Three series, not five. The palette is polarised — the same reason base16 draws"
  echo "# different accents per variant — and everything else either leaves the dark lightness"
  echo "# band or falls under 3:1 on ink"
  # shellcheck disable=SC2086 # the cycle is a word list on purpose
  mpl_cycler $mpl_cycle_dark
  echo
  mpl_colours ink paper jacket yuri
  echo
  mpl_common
} >"$out/ddlc-dark.mplstyle"

