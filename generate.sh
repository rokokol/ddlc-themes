    jq -Rn '[inputs | split("\t") | {
      key: .[0],
      value: (if .[1] == .[2] then .[1] else { dark: .[1], light: .[2] } end)
    }] | from_entries'
)
jq -n --argjson defs "$oc_defs" --argjson theme "$oc_theme" '{
  "$schema": "https://opencode.ai/theme.json",
  defs: $defs,
  theme: $theme
}' >"$out/ddlc-opencode.json"

